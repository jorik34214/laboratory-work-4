#!/bin/bash

# Перевіряємо, чи передані два параметри (назви каталогів)
if [ $# -ne 2 ]; then
    echo "Помилка: потрібно вказати два параметри – поточну та нову назву каталогу."
    exit 1
fi

OLD_DIR=$1
NEW_DIR=$2

# Перевіряємо, чи існує поточний каталог
if [ ! -d "$OLD_DIR" ]; then
    echo "Помилка: каталог '$OLD_DIR' не існує."
    exit 1
fi

# Змінюємо назву каталогу
mv "$OLD_DIR" "$NEW_DIR"

# Перевіряємо, чи вдалося змінити назву
if [ $? -eq 0 ]; then
    echo "Каталог '$OLD_DIR' успішно перейменовано у '$NEW_DIR'."
else
    echo "Помилка під час перейменування каталогу."
fi
